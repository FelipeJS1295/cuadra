/** "Ñuñoa" / "NUNOA" / "ñuñoa " -> "nunoa" */
const norm = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

const BY_NAME = new Map(COMUNAS.map(([name, code]) => [norm(name), code]));
// Nombres que se escriben distinto con frecuencia
const ALIAS: Record<string, string> = {
  stgo: 'santiago',
  'santiago centro': 'santiago',
  'est central': 'estacion central',
  pac: 'pedro aguirre cerda',
  'p a c': 'pedro aguirre cerda',
  coihaique: 'coyhaique',
  aisen: 'aysen',
  'puerto natales': 'natales',
  'llay llay': 'llaillay',
  llayllay: 'llaillay',
  paihuano: 'paiguano',
  trehuaco: 'treguaco',
};

/** Código de la comuna y de su región (sin ceros a la izquierda), o null si no se reconoce */
export function comunaCode(name: string | null | undefined): { comuna: string; region: string } | null {
  if (!name) return null;
  const n = norm(name);
  const code = BY_NAME.get(n) ?? BY_NAME.get(norm(ALIAS[n] ?? '')) ?? null;
  if (!code) return null;
  return { comuna: String(Number(code)), region: String(Number(code.slice(0, 2))) };
}
